#!/usr/bin/env python3
"""Emit the Game Plan as RDF, and give each gate a live Jira status.

A gate that is tied to a gap group inherits that group's work items through the Data
Journey's fixes, so "has stage 1 been unlocked?" becomes a query rather than a meeting.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gameplan as G  # noqa: E402
import journey as J   # noqa: E402

OUT = HERE.parent
ID = "https://migdl.midatahub.org/id/"
MAPID = ID + "map/gameplan-oct2026"


def esc(s):
    return str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def gate_status(live):
    """For each gate, the live state of every ticket its fixes depend on."""
    fix_of = {f["n"]: f for f in J.FIXES}
    out = {}
    for key, g in G.GATES.items():
        keys = []
        for fn in g["fixes"]:
            keys += list(fix_of[fn]["claim"].keys())
        rows = [{"k": k, "st": (live.get(k) or {}).get("st"),
                 "sc": (live.get(k) or {}).get("sc"),
                 "s": (live.get(k) or {}).get("s")} for k in keys]
        known = [r for r in rows if r["sc"]]
        done = sum(1 for r in known if r["sc"] == "Done")
        out[key] = {
            "tickets": rows, "done": done, "total": len(known),
            # a gate with no ticket cannot be tracked at all
            "tracked": bool(known),
            "state": ("untracked" if not known
                      else "open" if done == 0
                      else "partial" if done < len(known)
                      else "met"),
        }
    return out


def ttl(gs):
    L = ['@prefix migdl: <https://migdl.midatahub.org/ns#> .',
         '@prefix skos:  <http://www.w3.org/2004/02/skos/core#> .',
         '@prefix dct:   <http://purl.org/dc/terms/> .',
         '@prefix xsd:   <http://www.w3.org/2001/XMLSchema#> .',
         '',
         '# The MiGDL Delta Operations Game Plan (Oct 2026), as RDF.',
         '# Generated by work-ontology/generator/build_gameplan.py — do not edit by hand.',
         '',
         '<%s> a dct:BibliographicResource ;' % MAPID,
         '    dct:title "%s" ;' % esc(G.TITLE),
         '    dct:description "%s" ;' % esc(G.CAVEAT),
         '    dct:source "source/MiGDL_Delta_Operations_Game_Plan.pdf" .',
         '']

    for key, g in G.GATES.items():
        q = ['a migdl:Gate',
             'skos:prefLabel "%s"' % esc(g["label"]),
             'dct:title "%s"' % esc(g["name"]),
             'skos:definition "%s"' % esc(g["unlocks"])]
        for fn in g["fixes"]:
            q.append('migdl:dependsOnFix <%sfix/%d>' % (ID, fn))
        if not gs[key]["tracked"]:
            q.append('migdl:figureUnreadable false')
        L.append('<%sgate/%s> %s .' % (ID, key, ' ;\n    '.join(q)))
    L.append('')

    for st in G.STAGES:
        q = ['a migdl:OperatingStage',
             'skos:prefLabel "%s"' % esc(st["name"]),
             'migdl:stageNumber %d' % st["n"],
             'skos:definition "%s"' % esc(st["does"]),
             'dct:description "%s"' % esc(" \u00b7 ".join(st["correct"]))]
        if st["eta"]:
            q.append('migdl:eta "%s"' % esc(st["eta"]))
        if not st["throughput_readable"]:
            q.append('migdl:figureUnreadable true')
        for gk in st["gates"]:
            q.append('migdl:unlockedBy <%sgate/%s>' % (ID, gk))
        for i, _b in enumerate(G.BARS.get(st["n"], []), 1):
            q.append('migdl:hasBar <%sbar/%d-%d>' % (ID, st["n"], i))
        L.append('<%sstage/op-%d> %s .' % (ID, st["n"], ' ;\n    '.join(q)))

        for i, b in enumerate(G.BARS.get(st["n"], []), 1):
            r = ['a migdl:JobBar',
                 'skos:prefLabel "%s %s"' % (esc(b["n"]), esc(b["kind"])),
                 'migdl:forPipeline <%spipeline/%s>' % (ID, b["pipe"]),
                 'migdl:districtsPerTrigger "%s"' % esc(b["n"]),
                 'migdl:triggerKind "%s"' % esc(b["kind"]),
                 'dct:description "%s"' % esc(b["note"]),
                 'migdl:appliesInsert "%s"' % b["iud"]["I"],
                 'migdl:appliesUpdate "%s"' % b["iud"]["U"],
                 'migdl:appliesDelete "%s"' % b["iud"]["D"],
                 'dct:identifier "%s"' % esc(b["hop"])]
            L.append('<%sbar/%d-%d> %s .' % (ID, st["n"], i, ' ;\n    '.join(r)))
    L.append('')

    for i, d in enumerate(G.DECIDING, 1):
        L.append('<%squestion/%d> a migdl:OpenQuestion ;\n'
                 '    dct:title "%s" ;\n'
                 '    dct:description "%s" .'
                 % (ID, i, esc(d["head"]), esc(d["body"])))
    return "\n".join(L) + "\n"


def main():
    work = json.loads((OUT / "work.json").read_text())
    live = {i["k"]: {"st": i["st"], "sc": i["sc"], "s": i["s"]} for i in work["issues"]}
    gs = gate_status(live)
    (OUT / "migdl-gameplan.ttl").write_text(ttl(gs))

    (OUT / "gameplan.json").write_text(json.dumps({
        "title": G.TITLE, "lede": G.LEDE, "companion": G.COMPANION,
        "caveat": G.CAVEAT, "unreadable": G.UNREADABLE,
        "pipelines": G.PIPELINES, "stages": G.STAGES, "gates": G.GATES,
        "bars": G.BARS, "independence": G.INDEPENDENCE,
        "deciding": G.DECIDING, "layers": G.LAYERS, "gate_status": gs,
    }, separators=(",", ":")))

    print("stages %d | bars %d | gates %d" % (len(G.STAGES),
          sum(len(v) for v in G.BARS.values()), len(G.GATES)))
    for k, v in gs.items():
        print("  gate %-12s %-9s %s" % (k, v["state"],
              ("%d/%d tickets done" % (v["done"], v["total"])) if v["tracked"]
              else "no Jira ticket behind it"))


if __name__ == "__main__":
    main()
