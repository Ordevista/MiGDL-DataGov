#!/usr/bin/env python3
"""Emit the Data Journey map as RDF, and reconcile its ticket claims against Jira.

The map is a drawing with Jira keys written on it. This turns those keys into
assertions that can be checked: for every ticket the map cites, compare the status
the map claims against the status Jira holds now. A claim that no longer matches is
the map going stale, and a key Jira does not have at all is a broken reference.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import journey as J  # noqa: E402

OUT = HERE.parent
ID = "https://migdl.midatahub.org/id/"
MAPID = ID + "map/data-journey-v4"


def esc(s):
    return str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def reconcile(live):
    """live: {key: {'st':status,'sc':category,'s':summary}}. Returns per-ticket rows."""
    rows = []
    for f in J.FIXES:
        for key, claim in f["claim"].items():
            cur = live.get(key)
            if cur is None:
                state = "missing"       # cited, but Jira has no such issue
            elif claim is None:
                state = "unstated"      # the map names the ticket but asserts no status
            elif claim == cur["st"]:
                state = "agrees"
            else:
                state = "drifted"
            rows.append({"fix": f["n"], "gap": f.get("epic", ""), "key": key,
                         "claim": claim, "now": (cur or {}).get("st"),
                         "cat": (cur or {}).get("sc"), "sum": (cur or {}).get("s"),
                         "state": state})
    return rows


def not_in_jira(rows):
    """Everything the map commits to that Jira cannot currently track.

    Four kinds, each with a different remedy, so they are kept apart rather than
    lumped into one count: a fix with no ticket needs one raising; a broken reference
    needs correcting on the map; a product with no registration field needs a Jira
    admin change; a decision needs an owner, not a ticket.
    """
    out = []
    for f in J.FIXES:
        if not f["claim"]:
            out.append({"kind": "fix", "what": "Fix %d \u2014 %s" % (f["n"], f["head"]),
                        "why": "No Jira ticket at all. The map draws it \u201c%s\u201d." % f["chip"],
                        "where": f.get("epic", ""), "owners": f.get("owners", []),
                        "remedy": "Raise a ticket, or record that it is deliberately untracked."})
    for r in rows:
        if r["state"] == "missing":
            out.append({"kind": "broken", "what": r["key"],
                        "why": "Cited by fix %d, but no such issue exists in Jira." % r["fix"],
                        "where": r.get("gap", ""), "owners": [],
                        "remedy": "Correct the key on the map, or restore the issue."})
    for a in J.APPS:
        if not a["jira"]:
            out.append({"kind": "product", "what": a["name"],
                        "why": "Districts register for this application in the ingestion "
                               "tracker, but Jira has no [MiGDL] App Registration option for "
                               "it, so work on it cannot be attributed to the district that "
                               "asked for it.",
                        "where": "delivered by " + a["via"], "owners": [],
                        "remedy": "Add the field option so the two sources agree."})
    for i, d in enumerate(J.DECISIONS, 1):
        out.append({"kind": "decision", "what": d["head"],
                    "why": "An open decision, not an engineering task. Nothing in Jira will "
                           "resolve it, and work downstream of it is gated on the answer.",
                    "where": "owner: " + d["owner"], "owners": [d["owner"]],
                    "remedy": "Put it on a decision agenda with a date."})
    return out


def ttl(rows):
    L = ['@prefix migdl: <https://migdl.midatahub.org/ns#> .',
         '@prefix skos:  <http://www.w3.org/2004/02/skos/core#> .',
         '@prefix dct:   <http://purl.org/dc/terms/> .',
         '@prefix xsd:   <http://www.w3.org/2001/XMLSchema#> .',
         '',
         '# The MiGDL Data Journey map, %s (%s), as RDF.' % (J.MAP_VERSION, J.MAP_DATED),
         '# Generated by ontology/generator/build_journey.py — do not edit by hand.',
         '',
         '<%s> a dct:BibliographicResource ;' % MAPID,
         '    dct:title "MiGDL Data Journey: from the District SIS to the Apps" ;',
         '    dct:hasVersion "%s" ;' % J.MAP_VERSION,
         '    dct:issued "%s"^^xsd:date ;' % J.MAP_DATED,
         '    dct:description "Jira state as drawn is dated %s." .' % J.MAP_JIRA_ASOF,
         '']

    for s in J.STATIONS:
        p = ['a migdl:Station',
             'skos:prefLabel "%s"' % esc(s["name"]),
             'migdl:stationNumber %d' % s["n"],
             'migdl:plainName "%s"' % esc(s["name"]),
             'migdl:technicalName "%s"' % esc(s["tech"]),
             'skos:definition "%s"' % esc(s["does"])]
        for lay in s["layers"]:
            p.append('migdl:stationLayer <%slayer/%s>' % (ID, lay))
        for st in s["stages"]:
            p.append('migdl:stationStage <%sstage/%s>' % (ID, st))
        L.append('<%sstation/%s> %s .' % (ID, s["slug"], ' ;\n    '.join(p)))
    L.append('')

    fix_of_pain = {f["pain"]: f for f in J.FIXES}
    for pn in J.PAINS:
        u = '<%spain/%d>' % (ID, pn["n"])
        p = ['a migdl:PainPoint',
             'dct:title "%s"' % esc(pn["head"])]
        if pn.get("body"):
            p.append('dct:description "%s"' % esc(pn["body"]))
        if pn.get("asks"):
            p.append('migdl:userQuestion "%s"' % esc(pn["asks"]))
        if pn.get("src"):
            p.append('migdl:evidenceRef "%s"' % esc(pn["src"]))
        if pn.get("gap"):
            p.append('migdl:gapGroup "%s"' % pn["gap"])
        if pn.get("station"):
            p.append('migdl:atStation <%sstation/%s>' % (ID, pn["station"]))
        if pn["n"] in fix_of_pain:
            p.append('migdl:addressedBy <%sfix/%d>' % (ID, fix_of_pain[pn["n"]]["n"]))
        L.append('%s %s .' % (u, ' ;\n    '.join(p)))
    L.append('')

    for f in J.FIXES:
        p = ['a migdl:Fix',
             'dct:title "%s"' % esc(f["head"]),
             'dct:description "%s"' % esc(f["body"]),
             'migdl:mapChip "%s"' % esc(f["chip"])]
        if f.get("epic"):
            p.append('migdl:evidenceRef "%s"' % esc(f["epic"]))
        for key in f["claim"]:
            p.append('migdl:realisedBy <%swork/%s>' % (ID, key))
        L.append('<%sfix/%d> %s .' % (ID, f["n"], ' ;\n    '.join(p)))
    L.append('')

    # the claims themselves, each carrying whether Jira still agrees
    for r in rows:
        p = ['a migdl:TicketClaim',
             'migdl:claimsAbout <%swork/%s>' % (ID, r["key"]),
             'migdl:claimedBy <%s>' % MAPID]
        if r["claim"]:
            p.append('migdl:claimedStatus "%s"' % esc(r["claim"]))
        if r["state"] in ("agrees", "drifted"):
            p.append('migdl:agreesWithJira %s'
                     % ("true" if r["state"] == "agrees" else "false"))
        L.append('<%sclaim/%s-fix%d> %s .' % (ID, r["key"], r["fix"], ' ;\n    '.join(p)))
    L.append('')

    for p in J.PIPELINES:
        q = ['a migdl:Pipeline',
             'skos:prefLabel "Pipeline %s"' % p["id"],
             'dct:title "%s"' % esc(p["name"]),
             'migdl:runsInWindow "%s"' % esc(p["window"]),
             'migdl:districtsPerRun "%s"' % esc(p["rate"]),
             'migdl:maxDataAgeDays %d' % p["age_all"],
             'migdl:maxDataAgeDaysApp %d' % p["age_app"],
             'dct:description "%s"' % esc(p["note"])]
        if p.get("binding"):
            q.append('migdl:bindingConstraint true')
        for st in p["stations"]:
            q.append('migdl:atStation <%sstation/%s>' % (ID, st))
        L.append('<%spipeline/%s> %s .' % (ID, p["id"], ' ;\n    '.join(q)))
    L.append('')

    for n, j in enumerate(J.JOBS, 1):
        q = ['a migdl:EtlJob',
             'skos:prefLabel "%s"' % esc(j["name"]),
             'migdl:jobTech "%s"' % esc(j["tech"]),
             'skos:definition "%s"' % esc(j["does"])]
        if j.get("station"):
            q.append('migdl:atStation <%sstation/%s>' % (ID, j["station"]))
        L.append('<%sjob/%d> %s .' % (ID, n, ' ;\n    '.join(q)))
    L.append('')

    for c in J.CALLOUTS:
        L.append('<%scallout/%s> a migdl:Callout ;\n'
                 '    skos:prefLabel "Callout %s" ;\n'
                 '    dct:title "%s" ;\n'
                 '    dct:description "%s" ;\n'
                 '    migdl:atStation <%sstation/%s> ;\n'
                 '    migdl:evidenceRef "%s" .'
                 % (ID, c["id"], c["id"], esc(c["head"]), esc(c["body"]),
                    ID, c["station"], esc(c["fix"])))
    L.append('')

    for a in J.APPS:
        slug = re.sub(r"[^a-z0-9]+", "-", a["name"].lower()).strip("-")
        L.append('<%sproduct/%s> a migdl:DataProduct ;\n'
                 '    skos:prefLabel "%s" ;\n'
                 '    migdl:deliveredVia "%s" ;\n'
                 '    migdl:hasJiraRegistration %s .'
                 % (ID, slug, esc(a["name"]), esc(a["via"]),
                    "true" if a["jira"] else "false"))
    L.append('')

    for i, d in enumerate(J.DECISIONS, 1):
        L.append('<%sdecision/%d> a migdl:Decision ;\n'
                 '    dct:title "%s" ;\n'
                 '    dct:description "%s" ;\n'
                 '    dct:creator "%s" .'
                 % (ID, i, esc(d["head"]), esc(d["body"]), esc(d["owner"])))
    return "\n".join(L) + "\n"


def main():
    work = json.loads((OUT / "work.json").read_text())
    live = {i["k"]: {"st": i["st"], "sc": i["sc"], "s": i["s"]} for i in work["issues"]}
    rows = reconcile(live)
    (OUT / "migdl-journey.ttl").write_text(ttl(rows))

    bundle = {
        "map": {"version": J.MAP_VERSION, "dated": J.MAP_DATED,
                "jira_asof": J.MAP_JIRA_ASOF, "apps": J.APPS, "sequence": J.SEQUENCE,
                "fresh_asof": J.FRESHNESS_ASOF, "fresh_target": J.FRESHNESS_TARGET},
        "stations": J.STATIONS, "pains": J.PAINS, "fixes": J.FIXES,
        "decisions": J.DECISIONS, "recon": rows,
        "pipelines": J.PIPELINES, "jobs": J.JOBS, "callouts": J.CALLOUTS,
        "station_detail": J.STATION_DETAIL, "change_kinds": J.CHANGE_KINDS,
        "notjira": not_in_jira(rows),
    }
    (OUT / "journey.json").write_text(json.dumps(bundle, separators=(",", ":")))

    from collections import Counter
    c = Counter(r["state"] for r in rows)
    print("cited tickets      %d" % len(rows))
    for k in ("agrees", "drifted", "unstated", "missing"):
        print("  %-16s %3d" % (k, c[k]))
    print("fixes with no Jira ticket at all: %s"
          % [f["n"] for f in J.FIXES if not f["claim"]])
    print("pipelines %d | jobs %d | callouts %d | apps %d (%d with a Jira option)"
          % (len(J.PIPELINES), len(J.JOBS), len(J.CALLOUTS), len(J.APPS),
             sum(1 for a in J.APPS if a["jira"])))
    from collections import Counter as _C
    _n = _C(x["kind"] for x in bundle["notjira"])
    print("not tracked in Jira: %d  %s" % (len(bundle["notjira"]), dict(_n)))
    print("journey ttl        %.0f KB" % ((OUT / "migdl-journey.ttl").stat().st_size / 1024))


if __name__ == "__main__":
    main()
